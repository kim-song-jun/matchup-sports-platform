#!/usr/bin/env bash
# Writes the gitignored Config/Secrets.generated.xcconfig from the environment.
# Config/Shared.xcconfig includes it optionally, so a build without the key still compiles
# and simply leaves Kakao native sign-in off.
#
#   TEAMEET_KAKAO_ALPHA_NATIVE_APP_KEY       kr.co.teameet.alpha native key
#   TEAMEET_KAKAO_PRODUCTION_NATIVE_APP_KEY  kr.co.teameet native key
set -Eeuo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
generated="${repo_root}/apps/v1_ios/Config/Secrets.generated.xcconfig"
alpha_key="${TEAMEET_KAKAO_ALPHA_NATIVE_APP_KEY:-}"
production_key="${TEAMEET_KAKAO_PRODUCTION_NATIVE_APP_KEY:-}"

# The key becomes a URL scheme and an xcconfig value, so anything but alphanumerics is a
# mistake worth failing on rather than shipping.
for name in TEAMEET_KAKAO_ALPHA_NATIVE_APP_KEY TEAMEET_KAKAO_PRODUCTION_NATIVE_APP_KEY; do
  value="${!name:-}"
  if [[ -n "${value}" && ! "${value}" =~ ^[0-9a-f]{32}$ ]]; then
    echo "${name} must contain 32 lowercase hexadecimal characters." >&2
    exit 1
  fi
done

mkdir -p "$(dirname "${generated}")"
cat > "${generated}" <<EOT
// Generated by scripts/release/generate-ios-secrets-xcconfig.sh. Do not edit and do not commit.
TEAMEET_KAKAO_ALPHA_NATIVE_APP_KEY = ${alpha_key}
TEAMEET_KAKAO_PRODUCTION_NATIVE_APP_KEY = ${production_key}
EOT

echo "Wrote ${generated} (separate alpha/production Kakao inputs; empty input disables that environment)"
